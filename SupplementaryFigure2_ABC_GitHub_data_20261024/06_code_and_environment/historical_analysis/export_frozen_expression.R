invisible(Sys.setlocale('LC_CTYPE','English_United States.utf8'))
invisible(Sys.setlocale('LC_COLLATE','C'))
.libPaths(c('adsc_il17_rnaseq/.Rlibrary',.libPaths()))
suppressPackageStartupMessages({library(DESeq2);library(AnnotationDbi);library(org.Hs.eg.db)})
out <- 'analysis/supplementary_S3_20261008/source_data'
dir.create(out,recursive=TRUE,showWarnings=FALSE)
dds <- readRDS('HFF-1/round3_20260914/cache/sender_dds.rds')
stopifnot(nrow(dds)==14425,identical(deparse(design(dds)), '~replicate + time'))
# Only extract the saved fit and its original VST transformation. No DESeq refit.
v <- assay(vst(dds,blind=FALSE))
ann <- read.csv('HFF-1/round3_20260914/cache/sender_gene_annotation.csv')
meta <- as.data.frame(colData(dds));meta$sample_id <- rownames(meta)
write.csv(meta,file.path(out,'sample_metadata_frozen.csv'),row.names=FALSE)
write.csv(data.frame(gene_id=rownames(v),gene_name=ann$gene_name[match(rownames(v),ann$gene_id)],v,check.names=FALSE),file.path(out,'VST_all_14425_genes.csv'),row.names=FALSE)
write.csv(data.frame(gene_id=rownames(dds),counts(dds,normalized=TRUE),check.names=FALSE),file.path(out,'normalized_counts_all_14425_genes.csv'),row.names=FALSE)
ens<-sub('[.][0-9]+$','',rownames(dds))
map<-suppressMessages(AnnotationDbi::select(org.Hs.eg.db,keys=unique(ens),keytype='ENSEMBL',columns=c('ENTREZID','SYMBOL')))
write.csv(map,file.path(out,'Ensembl_Entrez_mapping_frozen_annotation.csv'),row.names=FALSE)
capture.output(sessionInfo(),file=file.path(out,'expression_export_sessionInfo.txt'))
cat('Exported existing-fit expression for',nrow(v),'genes and',ncol(v),'samples.\n')
